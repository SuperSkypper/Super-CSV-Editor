import esbuild from "esbuild";
import process from "process";
import { builtinModules } from 'node:module';

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = (process.argv[2] === "production");
// Harness-only build: bundles the internal GridController (not exported from
// main.ts) so the browser tests can drive the real grid instead of a mock.
const harness = (process.argv[2] === "harness");

if (harness) {
	await esbuild.build({
		entryPoints: ["test/harness/entry-grid.ts"],
		bundle: true,
		// The real obsidian module cannot load in a browser. `test/harness/
		// obsidian-shim.ts` supplies the handful of classes the grid touches.
		external: [...builtinModules],
		alias: { obsidian: "./test/harness/obsidian-shim.ts" },
		format: "iife",
		globalName: "__GRID__",
		target: "es2018",
		logLevel: "info",
		outfile: "test/harness/bundle-grid.js",
	});
	process.exit(0);
}

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
